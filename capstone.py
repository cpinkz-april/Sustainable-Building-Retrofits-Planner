import streamlit as st
import pandas as pd
import plotly.express as px

st.set_page_config(page_title="Executive Decision Page", layout="wide")
DATA_PATH = "capstone/building_metadata.csv"
df = pd.read_csv(DATA_PATH)

st.title("Executive Decision Page")
st.caption("การตัดสินใจด้านพลังงานอาคาร")

st.header("Decision Question")
st.write("บริษัทควรจัดสรรงบประมาณและลำดับความสำคัญในการติดตั้งมาตรการประหยัดพลังงาน (Energy Efficiency Measures) ที่อาคารประเภทใดและจุดปฏิบัติการใดก่อน เพื่อลดต้นทุนค่าไฟฟ้าและ Scope 2 Emissions ได้สูงสุด โดยให้ระยะเวลาคืนทุน (Payback Period) สั้นที่สุด?")

summary = (
    df.groupby("primary_use", as_index=False)
      .agg(
          total_square_feet=("square_feet","sum"),
          building_count=("building_id","count"),
          avg_year_built=("year_built","mean")
      )
      .sort_values("total_square_feet", ascending=False)
)

st.header("Executive KPIs")
current_year = pd.Timestamp.today().year
c1, c2, c3 = st.columns(3)
c1.metric("พื้นที่เป้าหมายสำหรับปรับปรุงประสิทธิภาพ", f"{df['square_feet'].sum():,.0f} sq ft")
c2.metric("อายุการใช้งานเฉลี่ยของอาคาร", f"{(current_year - df['year_built'].mean()):.0f} years")
c3.metric("อาคารลำดับความสำคัญสูงอาคารกลุ่มเป้าหมายเร่งด่วน", f"{(df['year_built'] < 1990).sum():,.0f}")
st.caption("สิ่งเหล่านี้คือเกณฑ์ชี้วัดขั้นคัดกรอง (Screening metrics) เพื่อจัดลำดับความสำคัญของการลงทุน ทั้งนี้ การคำนวณผลตอบแทนทางการเงิน (Financial ROI) และการลดการปล่อยก๊าซเรือนกระจกขอบเขตที่ 2 (Scope 2 reduction) จำเป็นต้องใช้ข้อมูลสาธารณูปโภคและข้อมูลปริมาณการใช้พลังงาน")

st.header("Evidence")

st.write("This chart helps answer: ประเภทอาคารใดมีโอกาส/ศักยภาพในการปรับปรุงประสิทธิภาพมากที่สุด?")
fig = px.bar(
    summary.head(10),
    x="primary_use",
    y="total_square_feet",
    title="Insight: กลุ่มอาคารเพื่อการศึกษาและอาคารสำนักงานมีโอกาสในการปรับปรุงประสิทธิภาพมากที่สุด"
)
st.plotly_chart(fig, width="stretch")

priority_by_use = (
    df.groupby("primary_use", as_index=False)
      .agg(
          total_square_feet=("square_feet", "sum"),
          avg_age=("year_built", "mean"),
          building_count=("building_id", "count")
      )
      .assign(avg_age=lambda x: 2026 - x["avg_age"])
      .sort_values(["total_square_feet", "avg_age"], ascending=[False, False])
)

st.write("This chart helps answer: ประเภทอาคารใดมีอายุการใช้งานมากที่สุด และจัดเป็นกลุ่มเร่งด่วนที่สุดที่ต้องเข้าไปดำเนินการ?")
fig_2 = px.scatter(
    priority_by_use,
    x="avg_age",
    y="total_square_feet",
    size="building_count",
    hover_name="primary_use",
    title="Insight: ประเภทอาคารที่มีอายุมากและมีขนาดพื้นที่อาคาร (Footprint) ขนาดใหญ่ ควรได้รับการจัดลำดับความสำคัญเป็นอันดับแรก",
    labels={"avg_age": "Average Age (years)", "total_square_feet": "Total Square Feet"}
)
st.plotly_chart(fig_2, width="stretch")

